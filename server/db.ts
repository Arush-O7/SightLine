// Postgres when DATABASE_URL is set, otherwise a local SQLite file.
// Queries are written with ? placeholders; the Postgres adapter turns them into $1, $2...
import { mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';

export type Row = Record<string, unknown>;

export interface Query {
  all<T = Row>(sql: string, ...params: unknown[]): Promise<T[]>;
  get<T = Row>(sql: string, ...params: unknown[]): Promise<T | undefined>;
  /** returns the number of rows changed */
  run(sql: string, ...params: unknown[]): Promise<number>;
}

export interface Database extends Query {
  kind: 'sqlite' | 'postgres';
  /** Runs `work` in one transaction. Inside it, use only the `q` it is given. */
  tx<T>(work: (q: Query) => Promise<T>): Promise<T>;
  close(): Promise<void>;
}

/** Bump when the schema below changes, so a long-running dev server migrates without a restart. */
const SCHEMA_VERSION = 7;

const TABLES = (pg: boolean) => {
  const id = pg ? 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY';
  const ref = pg ? 'BIGINT' : 'INTEGER';
  const ms = pg ? 'BIGINT' : 'INTEGER';
  return `
    CREATE TABLE IF NOT EXISTS users (
      id         ${id},
      email      TEXT NOT NULL UNIQUE,
      name       TEXT NOT NULL,
      pass_hash  TEXT NOT NULL DEFAULT '',
      pass_salt  TEXT NOT NULL DEFAULT '',
      created_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS sessions (
      token_hash TEXT PRIMARY KEY,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at ${ms} NOT NULL
    );
    CREATE INDEX IF NOT EXISTS sessions_user ON sessions(user_id);

    CREATE TABLE IF NOT EXISTS holds (
      show_id    TEXT NOT NULL,
      seat_id    TEXT NOT NULL,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at ${ms} NOT NULL,
      UNIQUE (show_id, seat_id)
    );
    CREATE INDEX IF NOT EXISTS holds_expiry ON holds(expires_at);

    CREATE TABLE IF NOT EXISTS bookings (
      id         TEXT PRIMARY KEY,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      show_id    TEXT NOT NULL,
      movie_id   TEXT NOT NULL,
      hall_id    TEXT NOT NULL,
      subtotal   INTEGER NOT NULL,
      fees       INTEGER NOT NULL,
      total      INTEGER NOT NULL,
      payment    TEXT NOT NULL,
      view_seat  TEXT,
      snapshot   TEXT,
      idem_key   TEXT NOT NULL,
      created_at ${ms} NOT NULL,
      UNIQUE (user_id, idem_key)
    );
    CREATE INDEX IF NOT EXISTS bookings_user ON bookings(user_id, created_at DESC);

    CREATE TABLE IF NOT EXISTS booking_seats (
      booking_id TEXT NOT NULL REFERENCES bookings(id) ON DELETE CASCADE,
      show_id    TEXT NOT NULL,
      seat_id    TEXT NOT NULL,
      UNIQUE (show_id, seat_id)
    );
    CREATE INDEX IF NOT EXISTS booking_seats_booking ON booking_seats(booking_id);

    CREATE TABLE IF NOT EXISTS payments (
      id         TEXT PRIMARY KEY,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      show_id    TEXT NOT NULL,
      amount     INTEGER NOT NULL,
      method     TEXT NOT NULL,
      instrument TEXT NOT NULL,
      status     TEXT NOT NULL,          -- paid | due | declined | refunded | void
      booking_id TEXT,
      created_at ${ms} NOT NULL
    );
    CREATE INDEX IF NOT EXISTS payments_booking ON payments(booking_id);

    CREATE TABLE IF NOT EXISTS password_resets (
      token_hash TEXT PRIMARY KEY,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS email_verifications (
      token_hash TEXT PRIMARY KEY,
      user_id    ${ref} NOT NULL REFERENCES users(id) ON DELETE CASCADE,
      expires_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS oauth_states (
      state_hash TEXT PRIMARY KEY,
      verifier   TEXT NOT NULL,
      nonce      TEXT NOT NULL,
      next_path  TEXT NOT NULL,
      expires_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS schedule_changes (
      id         ${id},
      action     TEXT NOT NULL,          -- add | cancel
      movie_id   TEXT NOT NULL,
      cinema_id  TEXT NOT NULL,
      screen_id  TEXT NOT NULL,
      date_key   TEXT NOT NULL,
      time       TEXT NOT NULL,
      created_by ${ref},
      created_at ${ms} NOT NULL,
      UNIQUE (cinema_id, screen_id, date_key, time, movie_id, action)
    );

    CREATE TABLE IF NOT EXISTS custom_titles (
      id         TEXT PRIMARY KEY,
      data       TEXT NOT NULL,          -- JSON TitleRecord
      created_by ${ref},
      created_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS zone_prices (
      hall_id    TEXT NOT NULL,
      zone_id    TEXT NOT NULL,
      price      INTEGER NOT NULL,
      updated_at ${ms} NOT NULL,
      PRIMARY KEY (hall_id, zone_id)
    );

    CREATE TABLE IF NOT EXISTS outbox (
      id         ${id},
      to_email   TEXT NOT NULL,
      subject    TEXT NOT NULL,
      html       TEXT NOT NULL,
      body_text  TEXT NOT NULL,
      kind       TEXT NOT NULL,
      created_at ${ms} NOT NULL
    );

    CREATE TABLE IF NOT EXISTS rate_limits (
      bucket     TEXT PRIMARY KEY,       -- action:visitor address
      hits       INTEGER NOT NULL,
      reset_at   ${ms} NOT NULL
    );
    CREATE INDEX IF NOT EXISTS rate_limits_reset ON rate_limits(reset_at);
  `;
};

/** Columns added after the first release: [table, column, sqlite type, postgres type]. */
const ADDED_COLUMNS: [string, string, string, string][] = [
  ['bookings', 'payment_status', "TEXT NOT NULL DEFAULT 'paid'", "TEXT NOT NULL DEFAULT 'paid'"],
  ['bookings', 'payment_ref', 'TEXT', 'TEXT'],
  ['bookings', 'instrument', 'TEXT', 'TEXT'],
  ['users', 'google_sub', 'TEXT', 'TEXT'],
  ['users', 'email_verified_at', 'INTEGER', 'BIGINT'],
  ['sessions', 'created_at', 'INTEGER', 'BIGINT'],
  ['sessions', 'last_seen_at', 'INTEGER', 'BIGINT'],
  ['sessions', 'user_agent', 'TEXT', 'TEXT'],
  ['users', 'role', "TEXT NOT NULL DEFAULT 'user'", "TEXT NOT NULL DEFAULT 'user'"],
];

const AFTER_COLUMNS = `CREATE UNIQUE INDEX IF NOT EXISTS users_google_sub ON users(google_sub)`;

async function openSqlite(): Promise<Database> {
  const { DatabaseSync } = await import('node:sqlite');
  // on Vercel only /tmp is writable, and it is wiped often: use DATABASE_URL there
  const fallback = process.env.VERCEL ? '/tmp/sightline.db' : 'data/sightline.db';
  if (process.env.VERCEL && !process.env.SIGHTLINE_DB) console.warn('[db] DATABASE_URL is not set; using a temporary SQLite file that Vercel can erase at any time.');
  const file = resolve(process.env.SIGHTLINE_DB || fallback);
  mkdirSync(dirname(file), { recursive: true });
  const db = new DatabaseSync(file);
  db.exec('PRAGMA journal_mode = WAL; PRAGMA foreign_keys = ON; PRAGMA busy_timeout = 4000;');

  const clean = (params: unknown[]) => params.map((p) => (p === undefined ? null : typeof p === 'boolean' ? Number(p) : p)) as never[];
  const direct: Query = {
    all: async <T>(sql: string, ...p: unknown[]) => db.prepare(sql).all(...clean(p)) as T[],
    get: async <T>(sql: string, ...p: unknown[]) => db.prepare(sql).get(...clean(p)) as T | undefined,
    run: async (sql: string, ...p: unknown[]) => Number(db.prepare(sql).run(...clean(p)).changes),
  };

  // One connection, so a transaction must not interleave with other requests' queries
  // while it awaits. Everything outside a transaction waits for it to finish.
  let busy: Promise<void> | null = null;
  const idle = async () => {
    while (busy) await busy;
  };
  const outside: Query = {
    all: async (sql, ...p) => (await idle(), direct.all(sql, ...p)),
    get: async (sql, ...p) => (await idle(), direct.get(sql, ...p)),
    run: async (sql, ...p) => (await idle(), direct.run(sql, ...p)),
  };

  const migrate = () => {
    db.exec(TABLES(false));
    for (const [table, col, type] of ADDED_COLUMNS) {
      const cols = new Set((db.prepare(`PRAGMA table_info(${table})`).all() as { name: string }[]).map((c) => c.name));
      if (!cols.has(col)) db.exec(`ALTER TABLE ${table} ADD COLUMN ${col} ${type}`);
    }
    db.exec(AFTER_COLUMNS);
  };
  migrate();

  return {
    kind: 'sqlite',
    ...outside,
    async tx(work) {
      await idle();
      let release!: () => void;
      busy = new Promise((r) => (release = r));
      db.exec('BEGIN IMMEDIATE');
      try {
        const out = await work(direct);
        db.exec('COMMIT');
        return out;
      } catch (err) {
        db.exec('ROLLBACK');
        throw err;
      } finally {
        busy = null;
        release();
      }
    },
    async close() {
      await idle();
      db.close();
    },
  };
}

/** `?` → `$1, $2…`. Our SQL never puts a question mark inside a string literal. */
function numbered(sql: string): string {
  let n = 0;
  return sql.replace(/\?/g, () => `$${++n}`);
}

async function openPostgres(url: string): Promise<Database> {
  const pg = (await import('pg')).default;
  // BIGINT (epoch ms, ids, counts) fits safely in a JS number for this data
  pg.types.setTypeParser(20, (v: string) => Number(v));
  const local = /@(localhost|127\.0\.0\.1|\[::1\])[:/]/.test(url);
  const pool = new pg.Pool({
    connectionString: url,
    max: Number(process.env.DATABASE_POOL_MAX) || 10,
    // hosted Postgres (Neon, Supabase, RDS) requires TLS; a local server usually has none
    ssl: process.env.DATABASE_SSL === '0' || (local && process.env.DATABASE_SSL !== '1') ? undefined : { rejectUnauthorized: false },
  });
  pool.on('error', (err) => console.error('[db] idle client error', err.message));

  const over = (exec: (text: string, values: unknown[]) => Promise<{ rows: Row[]; rowCount: number | null }>): Query => ({
    all: async <T>(sql: string, ...p: unknown[]) => (await exec(numbered(sql), p)).rows as T[],
    get: async <T>(sql: string, ...p: unknown[]) => (await exec(numbered(sql), p)).rows[0] as T | undefined,
    run: async (sql: string, ...p: unknown[]) => (await exec(numbered(sql), p)).rowCount ?? 0,
  });

  const migrate = async () => {
    const client = await pool.connect();
    try {
      // one migrator at a time, even with several app servers starting together
      await client.query('SELECT pg_advisory_lock(727274)');
      await client.query(TABLES(true));
      for (const [table, col, , type] of ADDED_COLUMNS) {
        await client.query(`ALTER TABLE ${table} ADD COLUMN IF NOT EXISTS ${col} ${type}`);
      }
      await client.query(AFTER_COLUMNS);
    } finally {
      await client.query('SELECT pg_advisory_unlock(727274)').catch(() => {});
      client.release();
    }
  };
  await migrate();

  return {
    kind: 'postgres',
    ...over((text, values) => pool.query(text, values)),
    async tx(work) {
      const client = await pool.connect();
      try {
        await client.query('BEGIN');
        const out = await work(over((text, values) => client.query(text, values)));
        await client.query('COMMIT');
        return out;
      } catch (err) {
        await client.query('ROLLBACK').catch(() => {});
        throw err;
      } finally {
        client.release();
      }
    },
    close: () => pool.end(),
  };
}

const g = globalThis as unknown as { __pxDatabase?: Promise<Database>; __pxDatabaseVersion?: number; __pxDatabaseUrl?: string };

/** The shared connection, opened (and migrated) on first use. */
export function getDb(): Promise<Database> {
  const url = process.env.DATABASE_URL?.trim() || '';
  if (g.__pxDatabase && g.__pxDatabaseUrl === url) {
    if (g.__pxDatabaseVersion !== SCHEMA_VERSION) {
      // The dev server reloaded this module with a newer schema. The open connection only
      // knows the old tables, so close it and reopen, which migrates with the new ones.
      g.__pxDatabaseVersion = SCHEMA_VERSION;
      const old = g.__pxDatabase;
      g.__pxDatabase = old
        .then((db) => db.close())
        .catch(() => {})
        .then(() => (url ? openPostgres(url) : openSqlite()));
    }
    return g.__pxDatabase;
  }
  g.__pxDatabaseUrl = url;
  g.__pxDatabaseVersion = SCHEMA_VERSION;
  g.__pxDatabase = (url ? openPostgres(url) : openSqlite()).catch((err) => {
    g.__pxDatabase = undefined;
    throw err;
  });
  return g.__pxDatabase;
}

export async function closeDb(): Promise<void> {
  const db = await g.__pxDatabase?.catch(() => undefined);
  g.__pxDatabase = undefined;
  await db?.close();
}

/** True for a uniqueness violation in either engine. */
export const isUniqueViolation = (err: unknown) =>
  (err as { code?: string })?.code === '23505' || /UNIQUE constraint failed/.test(String((err as Error)?.message));
